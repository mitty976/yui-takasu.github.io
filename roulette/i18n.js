  const idx = (lang) => (lang === 'fr' ? 1 : 0);

  /* 1語を訳す。辞書に無ければ日本語のまま返す */
  function L(name, lang) {
    if (!name || lang === 'ja' || lang === 'jp') return name;
    const e = T[name];
    if (!e) return name;
    return e[idx(lang)] || e[0] || name;
  }

  /* 「漆黒×山吹」「鏡×レコード×ティアラ」のように × でつないだ名前にも対応する。
     オッドアイの「オッドアイ（左／右）」のような括弧つきもここで分解する */
  function LX(name, lang) {
    if (!name || lang === 'ja' || lang === 'jp') return name;
    const odd = name.match(/^オッドアイ（(.+)／(.+)）$/);
    if (odd) {
      return L('オッドアイ', lang) + ' (' + L(odd[1], lang) + ' / ' + L(odd[2], lang) + ')';
    }
    if (name.indexOf('×') >= 0) {
      return name.split('×').map((s) => L(s.trim(), lang)).join(' × ');
    }
    return L(name, lang);
  }

