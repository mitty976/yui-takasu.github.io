    nOptions:  ['{0}種類', '{0} options', '{0} options'],
    allWithLocks: ['{0}（指定{1}つ）', '{0} ({1} locked)', '{0} ({1} figés)'],
    lockTitle: ['{0}を指定', 'Lock {0}', 'Figer : {0}'],
    pickUpTo:  ['{0}つまで選べます。', 'You can pick up to {0}.', "Vous pouvez en choisir jusqu'à {0}."],
